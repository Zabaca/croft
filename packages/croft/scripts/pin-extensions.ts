// Regenerates src/db/extension-pins.ts: the sha256 of each DuckDB extension croft's modes load, for each platform
// croft supports, read from DuckDB's official extension repository over HTTPS (DESIGN.md D117).
//
// Run it when the pinned DuckDB version changes or a mode needs another extension:
//   bun scripts/pin-extensions.ts
// It downloads every file (about 300 MB for one DuckDB version), unpacks it in memory and hashes the unpacked file,
// which is the file croft loads. Nothing is written but the pins. Review the diff: a changed checksum for a version
// already pinned means the repository's file changed under the same version.
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { gunzipSync } from "node:zlib";
import { DUCKDB_VERSION, EXTENSIONS, PLATFORMS } from "../src/db/extension-names.ts";

const REPO = "https://extensions.duckdb.org";
const out: Record<string, Record<string, { sha256: string; bytes: number }>> = {};
for (const platform of PLATFORMS) {
  out[platform] = {};
  for (const [name, file] of Object.entries(EXTENSIONS)) {
    const url = `${REPO}/v${DUCKDB_VERSION}/${platform}/${file}.duckdb_extension.gz`;
    const res = await fetch(url);
    if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
    const bytes = gunzipSync(Buffer.from(await res.arrayBuffer()));
    out[platform]![name] = { sha256: createHash("sha256").update(bytes).digest("hex"), bytes: bytes.length };
    console.log(platform, name, bytes.length, out[platform]![name]!.sha256);
  }
}

const lines: string[] = [
  "// GENERATED by scripts/pin-extensions.ts from DuckDB's official extension repository (DESIGN.md D117). Do not edit.",
  "// The sha256 and size of each UNPACKED extension file, per DuckDB platform. Checked before croft loads a file.",
  `import type { ExtensionName, Platform } from "./extension-names.ts";`,
  "",
  "export const EXTENSION_PINS: Record<Platform, Record<ExtensionName, { sha256: string; bytes: number }>> = {",
];
for (const [platform, exts] of Object.entries(out)) {
  lines.push(`  ${platform}: {`);
  for (const [name, p] of Object.entries(exts)) lines.push(`    ${name}: { sha256: "${p.sha256}", bytes: ${p.bytes} },`);
  lines.push("  },");
}
lines.push("};", "");
writeFileSync(new URL("../src/db/extension-pins.ts", import.meta.url), lines.join("\n"));
